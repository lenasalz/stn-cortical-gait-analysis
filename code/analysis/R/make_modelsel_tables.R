# ===================================================================
# Build tidy AIC/BIC model-comparison tables (CSV + LaTeX) for the
# supplement, from the SAME candidate models as the *_modelsel.R scripts.
# -------------------------------------------------------------------
# Inputs  (relative to code/analysis/R/):
#   ../../../data/derivatives/gerd/master_eeg_<norm>.csv
#   ../../../data/derivatives/gerd/master_dbs_<norm>.csv      (STN; ipsi/contra fit is identical)
# Outputs:
#   ../../../outputs/tables/lmm_modelsel_cortical.csv
#   ../../../outputs/tables/lmm_modelsel_STN.csv
#   ../../../outputs/tables/lmm_modelsel_STN.tex   (supplementary table)
# Run:  cd code/analysis/R && Rscript make_modelsel_tables.R
# ===================================================================
set.seed(42)
suppressMessages({ library(lme4); library(data.table) })

GERD <- "../../../data/derivatives/gerd"
OUT  <- "../../../outputs/tables"; dir.create(OUT, showWarnings = FALSE, recursive = TRUE)
norms <- c("basenorm", "avggait")
bands <- c("Theta", "Alpha", "Low_Beta", "High_Beta", "Gamma")
band_lab <- c(Theta="Theta", Alpha="Alpha", Low_Beta="Low beta",
              High_Beta="High beta", Gamma="Gamma")

fit_ml <- function(fstr, data)
  tryCatch(suppressMessages(suppressWarnings(
    lmer(as.formula(fstr), data = data, REML = FALSE,
         control = lmerControl(optimizer = "bobyqa", optCtrl = list(maxfun = 2e5))))),
    error = function(e) NULL)

rows_for <- function(df, defs, final_name, norm, band) {
  recs <- lapply(names(defs), function(nm) {
    m <- fit_ml(defs[[nm]], df); if (is.null(m)) return(NULL)
    data.frame(Normalisation = norm, Band = band_lab[[band]], Model = nm,
               k = attr(logLik(m), "df"), AIC = AIC(m), BIC = BIC(m),
               singular = isSingular(m), is_final = (nm == final_name),
               stringsAsFactors = FALSE)
  })
  tab <- do.call(rbind, recs)
  tab$dAIC <- tab$AIC - min(tab$AIC)
  tab$dBIC <- tab$BIC - min(tab$BIC)
  tab$best_AIC <- tab$dAIC == 0
  tab$best_BIC <- tab$dBIC == 0
  tab
}

# ---------------- CORTICAL ----------------
cort <- list()
for (norm in norms) {
  df <- fread(file.path(GERD, paste0("master_eeg_", norm, ".csv")))
  df <- df[df$Hemisphere == "Both", ]
  df$SubjectID<-factor(df$SubjectID); df$Group<-factor(df$Group)
  df$Area<-factor(df$Area); df$GaitPhase<-factor(df$GaitPhase); df$GaitCycle<-factor(df$Epoch)
  for (b in bands) {
    bc <- paste0("ERD_ERS_", b)
    defs <- list(
      group     = paste(bc, "~ Group + (1|SubjectID)"),
      int2      = paste(bc, "~ Group*Area + Group*GaitPhase + (1|SubjectID)"),
      int2_3way = paste(bc, "~ Group*Area + Group*GaitPhase + Group:GaitPhase:Area + (1|SubjectID)"),
      full3     = paste(bc, "~ Group*Area*GaitPhase + (1|SubjectID)"),
      FINAL     = paste(bc, "~ Group*Area + Group*GaitPhase + (1|SubjectID) + (1|GaitCycle:SubjectID)"))
    cort[[length(cort)+1]] <- rows_for(df, defs, "FINAL", norm, b)
  }
}
cort <- do.call(rbind, cort)

# ---------------- STN (anatomical; ipsi/contra fit is identical) ----------------
stn <- list()
for (norm in norms) {
  df <- fread(file.path(GERD, paste0("master_dbs_", norm, ".csv")))
  df <- df[df$Hemisphere %in% c("Left","Right"), ]
  df$SubjectID<-factor(df$SubjectID); df$Hemisphere<-factor(df$Hemisphere)
  df$GaitPhase<-factor(df$GaitPhase); df$GaitCycle<-factor(df$Epoch)
  for (b in bands) {
    bc <- paste0("ERD_ERS_", b)
    defs <- list(
      `additive`       = paste(bc, "~ Hemisphere + GaitPhase + (1|SubjectID)"),
      `FINAL`          = paste(bc, "~ Hemisphere * GaitPhase + (1|SubjectID)"),
      `interaction+cycle` = paste(bc, "~ Hemisphere * GaitPhase + (1|SubjectID) + (1|GaitCycle:SubjectID)"))
    stn[[length(stn)+1]] <- rows_for(df, defs, "FINAL", norm, b)
  }
}
stn <- do.call(rbind, stn)

# ---------------- write CSVs ----------------
num <- function(x) round(x, 1)
for (nm in c("cort","stn")) {
  d <- get(nm); d$AIC<-num(d$AIC); d$BIC<-num(d$BIC); d$dAIC<-num(d$dAIC); d$dBIC<-num(d$dBIC)
  fwrite(d, file.path(OUT, paste0("lmm_modelsel_", ifelse(nm=="cort","cortical","STN"), ".csv")))
}
cat("CSV written to", OUT, "\n")

# ---------------- STN LaTeX supplementary table ----------------
esc <- function(s) gsub("_", "\\\\_", s)
fmt <- function(x) formatC(x, format="f", digits=1, big.mark=",")
lines <- c(
"% Auto-generated by code/analysis/R/make_modelsel_tables.R — do not hand-edit.",
"\\begin{table}[ht]",
"\\centering",
"\\caption{STN linear mixed-model structure comparison (gERD/ERS). Each PD",
"subject contributes one STN hemisphere, so \\emph{Hemisphere} is a",
"between-subjects factor with \\texttt{(1\\,$\\vert$\\,Subject)} supplying its",
"error term. Models fit by maximum likelihood; AIC/BIC therefore comparable",
"across fixed and random terms. $\\Delta$ values are relative to the best model",
"in each band. The \\emph{FINAL} row is the model used in the manuscript",
"(\\texttt{Hemisphere\\,$\\times$\\,GaitPhase}). Anatomical and ipsi/contra",
"alignments give identical fits (factor relabelling only). The interaction is",
"retained to test the lateralisation-by-phase hypothesis; it is also the",
"AIC/BIC-supported structure in theta (and gamma by AIC), the bands carrying",
"the significant Hemisphere\\,$\\times$\\,GaitPhase effect.}",
"\\label{tab:stn_modelsel}",
"\\small",
"\\begin{tabular}{lllrrrrr}",
"\\toprule",
"Norm. & Band & Model & $k$ & AIC & $\\Delta$AIC & BIC & $\\Delta$BIC \\\\",
"\\midrule")
norm_disp <- c(basenorm="baseline", avggait="avg-gait")
for (norm in norms) {
  sub <- stn[stn$Normalisation == norm, ]
  for (b in unique(sub$Band)) {
    bb <- sub[sub$Band == b, ]
    for (i in seq_len(nrow(bb))) {
      r <- bb[i, ]
      mdl <- esc(r$Model); if (r$is_final) mdl <- paste0("\\textbf{", mdl, "}")
      ndisp <- if (i == 1) norm_disp[[norm]] else ""
      bdisp <- if (i == 1) b else ""
      lines <- c(lines, sprintf("%s & %s & %s & %d & %s & %s & %s & %s \\\\",
        ndisp, bdisp, mdl, r$k, fmt(r$AIC), fmt(r$dAIC), fmt(r$BIC), fmt(r$dBIC)))
    }
    lines <- c(lines, "\\addlinespace")
  }
  lines <- c(lines, "\\midrule")
}
lines <- c(lines[seq_len(length(lines)-1)],  # drop trailing \midrule
  "\\bottomrule",
  "\\end{tabular}",
  "\\end{table}")
writeLines(lines, file.path(OUT, "lmm_modelsel_STN.tex"))
cat("LaTeX written to", file.path(OUT, "lmm_modelsel_STN.tex"), "\n")
