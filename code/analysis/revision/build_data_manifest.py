"""Freeze the data version used for the revision analyses.

Purpose:  Record, for every local derivative that the revision analyses
          read, its size, modification time and SHA-256, so that "the
          analysed data version" is a defined object even though the
          derivatives themselves are gitignored.
Inputs:   data/derivatives/raw_clean/*.fif            (pickle-era export)
          data/derivatives/autoreject/*.npz           (fresh AutoReject masks)
          data/derivatives/epochs/*.fif
          data/derivatives/fooof/fooof_master.csv
          data/derivatives/gerd/*.csv
          code/analysis/R/Data/*.csv                  (LMM input tables)
          $RESIDUAL_DATA_ROOT/Final_filtered/rejection_mask_dico.pkl
              (legacy rejection mask; hashed only if the mount is present)
          code/analysis/config.yaml
Outputs:  docs/data_manifest_revision_<YYYY-MM-DD>.md
Author:   Lena
Date:     2026-10-12
Seed:     not applicable (no randomness)

Description:
  Walks the directories above, hashes every file and writes one Markdown
  table per directory. Files are listed by name only; names contain the
  anonymised subject codes (P4-xxxx), nothing else. Re-run before each
  submission and commit the manifest; if the manifest changes between two
  runs, the analysed data changed and the change must be explained in
  manuscript/revisions/2026-10_npjPD/analysis_log.md.

Usage:
  python code/analysis/revision/build_data_manifest.py
  python code/analysis/revision/build_data_manifest.py --date 2026-10-12
"""
from __future__ import annotations

import argparse
import hashlib
import os
import sys
from datetime import date, datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from _common import PROJECT_ROOT, load_config, resolve_paths  # noqa: E402

CHUNK = 1 << 20


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(CHUNK), b""):
            h.update(chunk)
    return h.hexdigest()


def manifest_rows(files: list[Path]) -> list[str]:
    rows = []
    for p in sorted(files):
        st = p.stat()
        mtime = datetime.fromtimestamp(st.st_mtime).strftime("%Y-%m-%d %H:%M")
        rows.append(f"| `{p.name}` | {st.st_size:,} | {mtime} | `{sha256_of(p)}` |")
    return rows


def section(title: str, root: Path, pattern: str) -> list[str]:
    files = [p for p in root.glob(pattern) if p.is_file()]
    out = [f"## {title}", "", f"Path: `{root.relative_to(PROJECT_ROOT) if root.is_relative_to(PROJECT_ROOT) else root}`  ",
           f"Files: {len(files)}", ""]
    if not files:
        out += ["_No files found._", ""]
        return out
    out += ["| File | Bytes | Modified | SHA-256 |", "|---|---|---|---|"]
    out += manifest_rows(files)
    out.append("")
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--date", default=date.today().isoformat(),
                        help="Date suffix of the manifest file (default: today).")
    args = parser.parse_args()

    config = load_config()
    paths = resolve_paths(config)
    out_path = PROJECT_ROOT / "docs" / f"data_manifest_revision_{args.date}.md"

    lines = [
        f"# Data manifest for the revision analyses ({args.date})",
        "",
        "Generated by `code/analysis/revision/build_data_manifest.py`. Lists the",
        "local derivatives read by the revision analyses with SHA-256 checksums.",
        "The `raw_clean` files are the pickle-era preprocessing export from which",
        "the submitted manuscript numbers were produced; the server `_proc.fif`",
        "files are a later export and are deliberately not part of this version.",
        "",
        f"Config: `code/analysis/config.yaml` (SHA-256 `{sha256_of(PROJECT_ROOT / 'code/analysis/config.yaml')}`)",
        "",
    ]
    lines += section("Clean continuous data (raw_clean)", paths.raw_clean_dir, "*.fif")
    lines += section("AutoReject masks", paths.derivatives_root / "autoreject", "*.npz")
    lines += section("Gait-warped epochs", paths.epochs_dir, "*.fif")
    lines += section("FOOOF master table", paths.fooof_dir, "fooof_master.csv")
    lines += section("gERD/ERS per-cycle tables", paths.derivatives_root / "gerd", "*.csv")
    lines += section("LMM input tables", PROJECT_ROOT / "code/analysis/R/Data", "*.csv")

    legacy_mask = paths.data_root / "Final_filtered" / "rejection_mask_dico.pkl"
    lines += ["## Legacy rejection mask (server)", ""]
    if legacy_mask.is_file():
        st = legacy_mask.stat()
        lines += [f"`{legacy_mask}`  ", f"Bytes: {st.st_size:,}; modified {datetime.fromtimestamp(st.st_mtime):%Y-%m-%d %H:%M}; "
                  f"SHA-256 `{sha256_of(legacy_mask)}`", ""]
    else:
        lines += [f"_Not reachable at `{legacy_mask}` when this manifest was built "
                  f"(RESIDUAL_DATA_ROOT={os.environ.get('RESIDUAL_DATA_ROOT', 'unset')}). "
                  "Re-run with the server mounted to record it._", ""]

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out_path.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
